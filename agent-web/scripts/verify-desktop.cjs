const { app, BrowserWindow } = require('electron')
const path = require('path')
const fs = require('fs')
const { randomUUID } = require('crypto')
const root = path.resolve(__dirname, '..')
const runtime = path.join(root, '..', 'agent-server', '.runtime')
fs.mkdirSync(runtime, { recursive: true })
app.setPath('userData', path.join(runtime, 'desktop-qa-profile'))
app.disableHardwareAcceleration()
app.whenReady().then(async () => {
  const archive = process.argv.includes('--source') ? root : path.join(root, 'release', 'win-unpacked', 'resources', 'app.asar')
  const window = new BrowserWindow({ show: false, width: 1320, height: 860,
    webPreferences: { preload: path.join(archive, 'electron', 'preload.cjs'),
      contextIsolation: true, nodeIntegration: false, offscreen: true, backgroundThrottling: false } })
  const tenant=randomUUID(), user=randomUUID()
  window.webContents.session.webRequest.onBeforeSendHeaders({ urls:['http://127.0.0.1:8080/api/*'] }, (details,callback) => {
    details.requestHeaders['X-Tenant-Id']=tenant
    details.requestHeaders['X-User-Id']=user
    callback({requestHeaders:details.requestHeaders})
  })
  const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms))
  const evaluate=async code=>{
    const result=await window.webContents.executeJavaScript('(async()=>{try{return {value:await eval('+JSON.stringify(code)+')}}catch(error){return {qaError:String(error)}}})()')
    if(result.qaError)throw Error('UI step failed: '+code+' :: '+result.qaError)
    return result.value
  }
  async function waitFor(code) {
    for(let attempt=0;attempt<800;attempt++) {
      if(await evaluate(code))return
      await delay(150)
    }
    throw new Error('UI condition timed out: '+code)
  }
  try {
    await window.loadFile(path.join(archive, 'dist', 'index.html'))
    await waitFor("!!document.querySelector('.composer-toolbar .model-picker-toggle') && !document.querySelector('.model-picker-toggle').disabled")
    await evaluate("document.querySelector('.model-picker-toggle').click()")
    await waitFor("!!document.querySelector('.configure-chat-model')")
    await evaluate("document.querySelector('.configure-chat-model').click()")
    await waitFor("!!document.querySelector('#model-url') && !document.querySelector('.model-dialog fieldset').disabled")
    const settingsState=await evaluate("({url:document.querySelector('#model-url').value,model:document.querySelector('#model-name').value,key:document.querySelector('#model-key').value,type:document.querySelector('#model-key').type})")
    if(!settingsState.url || !settingsState.model || settingsState.key || settingsState.type!=='password')throw Error('Model settings must load without exposing the saved Key')
    if(await evaluate("!!document.querySelector('.model-dialog input[id*=embedding]')"))throw Error('Embedding settings must not be editable')
    await evaluate("Array.from(document.querySelectorAll('.model-dialog .actions button')).find(b=>b.textContent.includes('测试连接')).click()")
    await waitFor("document.querySelector('.model-dialog .result')?.textContent.includes('连接正常')")
    await evaluate("document.querySelector('.model-dialog button[type=submit]').click()")
    await waitFor("document.querySelector('.model-dialog .result')?.textContent.includes('已保存')")
    await delay(200)
    fs.writeFileSync(path.join(runtime,'desktop-model-settings.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("document.querySelector('[aria-label=关闭模型配置]').click()")
    await waitFor("!document.querySelector('.model-dialog')")
    await evaluate("document.querySelector('.model-picker-toggle').click()")
    await waitFor("!!document.querySelector('.configure-chat-model')")
    await evaluate("document.querySelector('.configure-chat-model').click()")
    await waitFor("!!document.querySelector('#model-key') && !document.querySelector('.model-dialog fieldset').disabled")
    if(await evaluate("document.querySelector('#model-key').value !== ''"))throw Error('Stored Key was exposed after reopening settings')
    await evaluate("document.querySelector('[aria-label=关闭模型配置]').click()")

    await waitFor("document.querySelector('.model-picker-toggle')?.textContent.includes("+JSON.stringify(settingsState.model)+")")
    await evaluate("document.querySelector('.model-picker-toggle').click()")
    await waitFor("document.querySelector('.model-picker-menu')?.textContent.includes('自定义配置')")
    await delay(150)
    fs.writeFileSync(path.join(runtime,'desktop-composer-model-picker.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("Array.from(document.querySelectorAll('.model-picker-menu button')).find(b=>b.textContent.includes('使用系统默认模型')).click()")
    await waitFor("!document.querySelector('.model-picker-menu')")
    let content = ''
    for (let attempt = 0; attempt < 30; attempt++) {
      content = await window.webContents.executeJavaScript('document.body.innerText')
      if (content.includes('后端在线')) break
      await new Promise(resolve => setTimeout(resolve, 200))
    }
    for (const required of ['已归档', '暂无会话', '后端在线', '让想法']) {
      if (!content.includes(required)) throw new Error('Missing UI state: ' + required)
    }
    const hasClear = await window.webContents.executeJavaScript('!!document.querySelector("[aria-label=清空会话记录]")')
    if (!hasClear) throw new Error('Missing clear history control')
    const screenshots = []
    for (const theme of ['light','dark']) {
      await window.webContents.executeJavaScript('document.documentElement.dataset.theme=' + JSON.stringify(theme))
      await delay(200)
      const screenshot = await window.webContents.capturePage()
      const output = path.join(runtime, 'desktop-redesign-' + theme + '.png')
      fs.writeFileSync(output, screenshot.toPNG())
      screenshots.push(output)
    }
    await evaluate("document.documentElement.dataset.theme='light'; document.querySelector('.suggestion').click()")
    await waitFor("document.querySelector('.composer-input')?.value.includes('销售数据') && !document.querySelector('.send')?.disabled")
    await evaluate("document.querySelector('.send').click()")
    await waitFor("document.querySelector('.run-bar .badge')?.textContent.includes('已完成')")
    await delay(250)
    fs.writeFileSync(path.join(runtime,'desktop-redesign-conversation.png'),(await window.webContents.capturePage()).toPNG())
    window.setSize(1000,760)
    await delay(200)
    const overflow=await evaluate('document.documentElement.scrollWidth > window.innerWidth')
    if(overflow)throw new Error('Horizontal window overflow')
    fs.writeFileSync(path.join(runtime,'desktop-redesign-compact.png'),(await window.webContents.capturePage()).toPNG())
    window.setSize(1320,860)
    await evaluate("const input=document.querySelector('.composer-input');input.value='请使用 text_file_create 创建权限测试.md，正文只有 PERMISSION_UI_OK。先提交批准，不要创建其他文件。';input.dispatchEvent(new Event('input',{bubbles:true}));")
    await waitFor("!document.querySelector('.send').disabled")
    await evaluate("document.querySelector('.send').click()")
    await waitFor("document.querySelector('.approval-arguments')?.textContent.includes('PERMISSION_UI_OK')")
    await delay(150)
    fs.writeFileSync(path.join(runtime,'desktop-permission-request.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("document.querySelector('.approve .btn-danger').click()")
    await waitFor("document.querySelector('.run-bar .badge')?.textContent.includes('已失败')")
    await evaluate("Array.from(document.querySelectorAll('.tab')).find(e=>e.textContent.includes('工具与技能')).click()")
    await waitFor("document.querySelectorAll('.tool-card').length===48")
    if(await evaluate("document.querySelector('[data-tool=command_run] .enable-tool').checked"))throw Error('Commands should default to disabled')
    await delay(150)
    fs.writeFileSync(path.join(runtime,'desktop-capabilities.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("Array.from(document.querySelectorAll('.cap-tabs button')).find(b=>b.textContent.includes('工作区文件')).click()")
    await waitFor("!!document.querySelector('.workspace-section input[type=file]')")
    await evaluate("const transfer=new DataTransfer();transfer.items.add(new File(['print(1+2)'],'desktop-code.py',{type:'text/plain'}));const input=document.querySelector('.workspace-section input[type=file]');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));")
    await waitFor("document.querySelector('.workspace-file')?.textContent.includes('desktop-code.py')")
    await evaluate("Array.from(document.querySelectorAll('.cap-tabs button')).find(b=>b.textContent.includes('技能库')).click()")
    await waitFor("document.querySelectorAll('.skill-card').length>=7")
    await delay(150)
    fs.writeFileSync(path.join(runtime,'desktop-skills.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("Array.from(document.querySelectorAll('.tab')).find(e=>e.textContent.includes('知识与记忆')).click()")
    await waitFor("!!document.querySelector('.upload-zone') && !!document.querySelector('[role=switch]')")
    await evaluate("const transfer=new DataTransfer();transfer.items.add(new File(['差旅住宿标准：每晚600元。'], '桌面上传验证.md', {type:'text/markdown'}));const input=document.querySelector('input[type=file]');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));")
    await waitFor("document.querySelector('.documents')?.textContent.includes('桌面上传验证.md')")
    const auth={'X-Tenant-Id':tenant,'X-User-Id':user,'Content-Type':'application/json'}
    const newSession=await fetch('http://127.0.0.1:8080/api/sessions',{method:'POST',headers:auth,body:JSON.stringify({title:'桌面记忆验证'})}).then(r=>r.json())
    await fetch('http://127.0.0.1:8080/api/sessions/'+newSession.sessionId+'/runs',{method:'POST',headers:auth,body:JSON.stringify({message:'以后请用中文回答。'})})
    await waitFor("document.querySelector('.memory-item')?.textContent.includes('中文')")
    await delay(200)
    fs.writeFileSync(path.join(runtime,'desktop-knowledge-memory.png'),(await window.webContents.capturePage()).toPNG())
    await evaluate("document.querySelector('.memory-actions button').click()")
    await waitFor("!!document.querySelector('.dialog textarea')")
    await evaluate("const field=document.querySelector('.dialog textarea');field.value='用户偏好中文与简短段落';field.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('.dialog .btn-primary').click()")
    await waitFor("document.querySelector('.memory-item')?.textContent.includes('已纠正') && !document.querySelector('.overlay')")
    await evaluate("document.querySelectorAll('.memory-actions button')[1].click()")
    await waitFor("!!document.querySelector('.dialog .btn-danger')")
    await evaluate("document.querySelector('.dialog .btn-danger').click()")
    await waitFor("!document.querySelector('.memory-item')")
    const documents=await fetch('http://127.0.0.1:8080/api/knowledge/documents',{headers:auth}).then(r=>r.json())
    for(const document of documents.documents)await fetch('http://127.0.0.1:8080/api/knowledge/documents/'+document.documentId,{method:'DELETE',headers:auth})
    const cleared=await fetch('http://127.0.0.1:8080/api/sessions',{method:'DELETE',headers:{'X-Tenant-Id':tenant,'X-User-Id':user}})
    if(!cleared.ok)throw new Error('QA session cleanup failed')
    await fetch('http://127.0.0.1:8080/api/model-settings',{method:'DELETE',headers:auth})
    console.log(JSON.stringify({ packagedUI: 'ok', emptyHistory: true, backend: 'online', screenshots }))
    window.destroy()
    app.exit(0)
  } catch (error) {
    console.error(error.message)
    window.destroy()
    app.exit(1)
  }
})
